kotlin {
    // A JVM target keeps the module an ordinary participant in `./gradlew build` on Linux CI.
    jvm()
    // Loupe for Android: :android-app depends on this module as the iPhone app does on LoupeKit.
    if (androidHost) {
        androidTarget {
            compilerOptions {
                jvmTarget.set(JvmTarget.JVM_17)
            }
        }
    }

    if (appleHost) {
        val xcf = XCFramework("LoupeKit")
        listOf(iosArm64(), iosSimulatorArm64()).forEach { target ->
            target.binaries.framework {
                baseName = "LoupeKit"
                isStatic = true
                export(project(":engine"))
                export(project(":templates"))
                export(project(":game"))
                export(project(":persistence"))
                export(project(":sources-common"))
                if (layaIos != null) {
                    export(layaIos)
                    export(project(":backend-laya-common"))
                }
                xcf.add(this)
            }
        }
    }

    // jvmCommon: the JVM actuals, shared as is by the desktop JVM and Android (docs/ANDROID-PLAN.md,
    // "no logic forks").
    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalKotlinGradlePluginApi::class)
    applyDefaultHierarchyTemplate {
        common {
            group("jvmCommon") {
                withJvm()
                withAndroidTarget()
            }
        }
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateSharedHosts)
            kotlin.srcDir(generateModelPrior)
        }
        commonMain.dependencies {
            api(project(":engine"))
            api(project(":templates"))
            // The game (Riverflight) for the iPhone app: rules, pilots, GameSessions, HostedDecider.
            api(project(":game"))
            // The ledger on the phone (epic #7 child 1): PhoneLedger, the files, the F4 export.
            api(project(":persistence"))
            // Sources on the phone (epic #7 child 2): SourceItem, the common extractors and scanner, the cache.
            api(project(":sources-common"))
        }
        commonTest {
            kotlin.srcDir(generateTestPaths)
            kotlin.srcDir(parityEvaluator)
            dependencies {
                implementation(kotlin("test"))
            }
        }
        // The sample's PDFs need a real reader: PDFBox (through :sources-desktop) on the JVM,
        // PDFKit on the iOS simulator — the readers each app uses. Android's unit tests run on the
        // host JVM and share the JVM's (jvmCommonTest); the phone's own PDF reader comes with the
        // Android sources milestone (A4), and is never PDFBox.
        getByName("jvmCommonTest").dependencies {
            implementation(project(":sources-desktop"))
        }
        // Tests only: the gated real-model measurement (ModelFixesMeasurementTest) loads Laya through
        // the ONNX backend, as :game's gated tests do. Never on the kit's runtime classpath.
        jvmTest.dependencies {
            implementation(project(":backend-onnx"))
        }
        if (appleHost && layaIos != null) {
            iosMain {
                // Only compiled when Laya for iOS is present, since it calls into it.
                kotlin.srcDir("src/iosLaya/kotlin")
                dependencies {
                    api(layaIos)
                    api(project(":backend-laya-common"))
                }
            }
        }
    }
}

