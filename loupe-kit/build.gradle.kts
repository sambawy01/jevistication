            include("laya-multilingual/tokenizer/tokenizer.json", "laya-multilingual-onnx/laya-multilingual-choice.int8.onnx")
        },
    ).withPropertyName("layaModels").withPathSensitivity(PathSensitivity.RELATIVE).optional()
